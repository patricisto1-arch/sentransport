export const DICTIONNAIRES = { fr, en } satisfies Record<
  Langue,
  Record<CleTraduction, string>
>;

export function traduire(
  langue: Langue,
  cle: CleTraduction,
  variables?: Record<string, string | number>,
) {
  const base = DICTIONNAIRES[langue]?.[cle] ?? DICTIONNAIRES.fr[cle] ?? cle;
  if (!variables) return base;
  return Object.entries(variables).reduce(
    (acc, [nom, valeur]) => acc.replaceAll(`{${nom}}`, String(valeur)),
    base,
  );
}
